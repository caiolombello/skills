#!/usr/bin/env python3
"""Check CATALOG.md against source metadata; write only with --apply."""
import sys

sys.dont_write_bytecode = True
import argparse
import html
from pathlib import Path

try:
    from doctor import diagnose
    from skill_metadata import manifests, metadata
except ImportError:
    sys.exit("Install check dependencies with: python3 -m pip install -r setup/requirements-checks.txt")


def cell(text):
    return html.escape(" ".join(text.split()), quote=False).replace("|", "&#124;")


def render(repo):
    report = diagnose(repo)
    errors = [item for item in report["findings"] if item["level"] == "error"]
    if errors:
        raise ValueError("invalid source; run setup/doctor.py for details")
    profiles = manifests(repo)
    lines = [
        "# Skill catalog", "",
        "<!-- Generated by setup/build_catalog.py; edit source metadata/manifests, not this file. -->", "",
        f"{len(report['skills'])} source skills. Descriptions below are discovery metadata, not runtime certifications.", "",
        "Profiles are additive selections for `setup/install.py --manifest install-manifests/PROFILE.txt`.",
        "They do not remove existing skills. No profile is installed by default.", "",
        "File installation, native discovery, and successful runtime use are separate checks.",
        "See [provider setup and verification boundaries](setup/README.md); a provider path does not prove activation.", "",
        "| Skill | When to use | Public profiles | Behavioral cases |",
        "| --- | --- | --- | --- |",
    ]
    for name in report["skills"]:
        description = metadata(repo / name)["description"]
        selected = ", ".join(f"[{p}](install-manifests/{p}.txt)" for p, entries in profiles.items() if name in entries) or "—"
        evaluations = repo / name / "evals/scenarios.json"
        cases = f"[scenarios]({name}/evals/scenarios.json)" if evaluations.is_file() else "—"
        lines.append(f"| [{name}]({name}/SKILL.md) | {cell(description)} | {selected} | {cases} |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--apply", action="store_true")
    args = parser.parse_args()
    repo = args.repo.resolve()
    target = repo / "CATALOG.md"
    try:
        if target.is_symlink():
            raise ValueError("refusing symlink catalog")
        expected = render(repo)
        if target.exists() and target.read_text(encoding="utf-8") == expected:
            print("Catalog matches source metadata and profiles")
            return 0
        if not args.apply:
            print("Catalog missing or stale; regenerate with python3 setup/build_catalog.py --apply")
            return 1
        target.write_text(expected, encoding="utf-8")
        print("Generated CATALOG.md")
        return 0
    except (OSError, ValueError) as error:
        parser.exit(2, f"Cannot build catalog: {error}\n")


if __name__ == "__main__":
    sys.exit(main())
